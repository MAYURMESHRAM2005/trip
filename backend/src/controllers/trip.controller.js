/**
 * Self-heal stored validation: re-run the deterministic Final Validator
 * against the itinerary's current days before serving it. Validation issues
 * are persisted at generation time, so trips generated by an older validator
 * build would otherwise show stale warnings (e.g. false "overlaps")
 * forever. The deterministic checks are pure and cheap - recompute them on
 * read and persist only when the result actually changed.
 */
/**
 * Self-heal stored prices: fill every missing/zero price with a centralized
 * category-based estimate (flagged ESTIMATE) before serving an itinerary.
 * Trips generated by older builds (or by providers without pricing data)
 * otherwise render a "—" for every unpriced item. Live/real prices are never
 * touched, and day totals are recomputed from the actual item costs.
 * Runs on read and persists only when something actually changed.
 */
async function refreshPrices(itinerary, trip) {
  if (!itinerary || !trip) return;
  const days = itinerary.days;
  if (!Array.isArray(days) || !days.length) return;

  const currency = itinerary.currency || trip.budget?.currency || 'INR';
  const partySize = Math.max(1, Number(trip.travelers?.adults) + Number(trip.travelers?.children) || 1);
  const rooms = budgetService.roomsForParty({ adults: trip.travelers?.adults, children: trip.travelers?.children });
  const allocation = itinerary.budgetAllocation || budgetService.allocationForStyle(
    trip.preferences?.travelStyle || 'standard',
    trip.budget?.total || 0
  );
  const nights = Math.max(0, days.length - 1);
  const transportAlloc = allocation.transport?.amount || 0;
  const hotelAllocPerNight = allocation.hotels?.amount && nights > 0 ? allocation.hotels.amount / nights / rooms : 0;
  const hotelFromItinerary = itinerary.accommodation?.pricePerNight > 0 ? itinerary.accommodation.pricePerNight : 0;
  const outboundEstimate = Math.round(transportAlloc * 0.35 * 100) / 100;
  const localTransportDaily = Math.round((transportAlloc * 0.3) / Math.max(1, days.length) * 100) / 100;
  // Per-person budget caps for ESTIMATED prices only (live prices are never capped).
  const mealPerPersonCap = Math.round((allocation.food?.amount || 0) / Math.max(1, days.length) / 3 / partySize * 100) / 100;
  const activityPerPersonCap = Math.round((allocation.activities?.amount || 0) / Math.max(1, days.length) / partySize * 100) / 100;

  let changed = false;
  for (const day of days) {
    // Keep live hotel rates untouched; cap ESTIMATED rates by the budget.
    const rawNightly = day.overnight?.pricePerRoomNight > 0 ? day.overnight.pricePerRoomNight : hotelFromItinerary;
    const hotelNightly = (day.overnight?.isLive === true || itinerary.accommodation?.isLive === true)
      ? rawNightly
      : (hotelAllocPerNight > 0 ? Math.min(rawNightly || hotelAllocPerNight, hotelAllocPerNight * 1.05) : rawNightly);
    // Prefer a leg-based local transport estimate over the budget envelope so
    // each day's fare reflects its actual travel movement.
    const legCost = pricingService.localTransportLegEstimate((day.activities || []).map((a) => a.travel));
    const localDaily = legCost > 0 ? legCost : localTransportDaily;
    for (const act of day.activities || []) {
      const res = pricingService.normalizeActivityCost(act, {
        partySize,
        currency,
        hotelNightly: hotelNightly || hotelAllocPerNight,
        hotelDaily: hotelAllocPerNight,
        maxHotelNightly: hotelAllocPerNight || 0,
        maxMealPerPerson: mealPerPersonCap,
        maxActivityPerPerson: activityPerPersonCap,
        maxTravelCost: localTransportDaily,
        localTransportDaily: localDaily,
        outboundEstimate,
      });
      if (res.changed) changed = true;
    }
  }

  if (!changed) return;

  // Recompute per-day totals from the (now complete) item costs.
  itineraryService.finalizeDayCosts(days, { partySize, totalBudget: trip.budget?.total });
  itinerary.totalEstimatedCost = itineraryService.computeItineraryCost(days);
  try {
    for (const day of days) {
      if (typeof day.markModified === 'function') day.markModified('costBreakdown');
    }
    await itinerary.save();
  } catch {
    // Non-fatal: a persistence failure must not block serving the trip.
  }
}

async function refreshValidation(itinerary, trip) {
  if (!itinerary || !trip) return;
  const fresh = finalValidatorAgent.runDeterministic({
    days: itinerary.days,
    budget: trip.budget?.total ?? 0,
    totalEstimatedCost: itinerary.totalEstimatedCost ?? trip.totalEstimatedCost ?? 0,
    destination: trip.destination,
    origin: trip.origin || '',
    prefs: trip.preferences || {},
  });
  const old = itinerary.validation || {};
  // The Itinerary schema persists issues/warnings as plain strings; validator
  // issues may arrive as objects ({ type, day, providerId, message }), so map
  // them to their message text before comparing/persisting.
  const toText = (arr = []) => (arr || []).map((i) => (typeof i === 'string' ? i : (i && (i.message || i.type)) || String(i)));
  const freshIssues = toText(fresh.issues);
  const freshWarnings = toText(fresh.warnings);
  const changed =
    old.passed !== fresh.passed ||
    JSON.stringify(old.issues || []) !== JSON.stringify(freshIssues) ||
    JSON.stringify(old.warnings || []) !== JSON.stringify(freshWarnings);
  if (changed) {
    itinerary.set('validation', {
      passed: fresh.passed,
      issues: freshIssues,
      warnings: freshWarnings,
      validatedAt: new Date(),
    });
    try {
      await itinerary.save();
    } catch {
      // Non-fatal: a persistence failure must not block serving the trip.
    }
  }
}

export const generate = asyncHandler(async (req, res) => {
  logger.entry('[CTRL:trip]', 'generate', { userId: req.user._id, destination: req.body.destination, origin: req.body.origin, startDate: req.body.startDate, endDate: req.body.endDate, totalBudget: req.body.totalBudget });
  const request = { ...req.body, title: sanitizeText(req.body.title, 160) || undefined };
  const result = await orchestrator.generateTrip({ user: req.user, request });
  logger.exit('[CTRL:trip]', 'generate', { status: 'success', tripId: result.trip?._id, pipelineMs: result.pipelineMs });
  res.status(201).json(
    ApiResponse.created('Trip generated by multi-agent pipeline', result)
  );
});

