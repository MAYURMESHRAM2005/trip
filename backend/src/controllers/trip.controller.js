/**
 * Move an activity to a different day (chatbot action "Move this attraction to tomorrow").
 */
export const moveActivity = asyncHandler(async (req, res) => {
  const { fromDay, activityId, toDay } = req.body;
  logger.entry('[CTRL:trip]', 'moveActivity', { tripId: req.params.id, fromDay, activityId, toDay });
  const trip = await Trip.findOne({ _id: req.params.id, user: req.user._id });
  if (!trip) throw ApiError.notFound('Trip not found');
  const itinerary = await Itinerary.findOne({ trip: trip._id });
  if (!itinerary) throw ApiError.notFound('Itinerary not found');

  const source = itinerary.days.find((d) => d.dayNumber === fromDay);
  const target = itinerary.days.find((d) => d.dayNumber === toDay);
  if (!source || !target) throw ApiError.badRequest('Invalid day numbers');

  const actIndex = source.activities.findIndex((a) => a._id?.toString() === activityId || a.title === activityId);
  if (actIndex === -1) throw ApiError.badRequest('Activity not found');

  const [moved] = source.activities.splice(actIndex, 1);
  target.activities.push(moved);
  await refreshPrices(itinerary, trip);
  await refreshValidation(itinerary, trip);
  res.json(ApiResponse.ok(`Moved "${moved.title}" to Day ${toDay}`, { itinerary }));
});

export const replaceHotel = asyncHandler(async (req, res) => {
  logger.entry('[CTRL:trip]', 'replaceHotel', { tripId: req.params.id, userId: req.user._id });
  const trip = await Trip.findOne({ _id: req.params.id, user: req.user._id });
  if (!trip) throw ApiError.notFound('Trip not found');
  const itinerary = await Itinerary.findOne({ trip: trip._id });
  if (!itinerary) throw ApiError.notFound('Itinerary not found');

  const hotelAgent = (await import('../agents/hotel.agent.js')).default;
  const allocation = budgetService.allocationForStyle(trip.preferences?.travelStyle || 'standard', trip.budget.total);
  const nights = Math.max(0, Math.ceil((new Date(trip.endDate) - new Date(trip.startDate)) / (1000 * 60 * 60 * 24)));
  const rooms = budgetService.roomsForParty({ adults: trip.travelers?.adults || 1, children: trip.travelers?.children || 0 });
  const maxPrice = (allocation.hotels?.amount || 0) > 0 && nights > 0 && rooms > 0
    ? allocation.hotels.amount / nights / rooms
    : (allocation.hotels?.amount || 0);
  const hotelResult = await hotelAgent.run({
    destination: trip.destination,
    checkIn: new Date(trip.startDate).toISOString().slice(0, 10),
    checkOut: new Date(trip.endDate).toISOString().slice(0, 10),
    adults: trip.travelers?.adults || 1,
    rooms,
    maxPrice,
    totalBudget: trip.budget.total,
    hotelPreference: trip.preferences?.hotelPreference || '',
    userId: req.user._id.toString(),
  });

  const newHotel = hotelResult.data?.recommended || hotelResult.data?.hotels?.[0];
  itinerary.accommodation = newHotel
    ? {
        name: newHotel.name,
        address: newHotel.address || '',
        pricePerNight: newHotel.price?.amount ?? null,
        isLive: hotelResult.data?.isLive === true,
        source: 'amadeus-hotels',
      }
    : { name: '', isLive: false, source: 'unavailable' };
  await itinerary.save();
  await refreshValidation(itinerary, trip);

  res.json(
    ApiResponse.ok(
      newHotel ? `Hotel replaced with ${newHotel.name}` : hotelResult.data?.message || 'No alternative hotel found',
      { itinerary, hotel: newHotel, message: hotelResult.data?.message }
    )
  );
});

